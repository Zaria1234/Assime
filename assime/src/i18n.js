export const DICTIONNAIRES = { fr, en, ewe }

const pluriel = (langue, n) => (langue === 'en' ? n !== 1 : n > 1)

function chercher(langue, cle, n) {
  const d = DICTIONNAIRES[langue] || fr
  if (n != null && pluriel(langue, n)) {
    if (d[cle + '.pl'] != null) return d[cle + '.pl']
    if (d[cle] == null && fr[cle + '.pl'] != null) return fr[cle + '.pl']
  }
  return d[cle] ?? fr[cle]
}

/** Texte de la clé dans la langue (repli : français, puis defaut, puis la clé elle-même) */
export function traduire(langue, cle, vars, defaut) {
  const brut = chercher(langue, cle, vars?.n) ?? defaut ?? cle
  return vars ? brut.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m)) : brut
}

/** Nom d'une catégorie, d'un filtre ou d'un type de repère (en français : le nom lui-même) */
export const traduireCategorie = (langue, cat) => traduire(langue, 'cat.' + cat, null, cat)
